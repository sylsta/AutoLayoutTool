    def run_from_mapCanvas(self):
        """
        Creates a layout with a map of the current interface extent, with legend, scalebar and north arrow
        :return: None
        """

        extent = self.iface.mapCanvas().extent()

        self.draw_layout_from_extent(extent)

    def run_from_rectangle(self, startX, startY, endX, endY):
        """

        """
        extent = QgsRectangle(startX, startY, endX, endY)
        if extent.width() == 0 or extent.height() == 0:
            self.notify(self.tr(u'Click and drag on the map to draw a rectangle'), Qgis.Warning)
            return
        self.draw_layout_from_extent(extent)

    def run_from_layers(self):
        """
        Opens the layer selection dialog, then creates a layout covering the extent of the checked layers.
        Checked layers are only used to compute the extent: as in the other modes, the map and the legend
        show the layers visible in the map canvas (a checked hidden layer frames the map but is not shown).
        """
        project = QgsProject.instance()
        all_layers = list(project.mapLayers().values())
        if not all_layers:
            self.notify(self.tr(u'There is no layer in the project'), Qgis.Warning)
            return
        if not any(layer_has_extent(l) for l in all_layers):
            self.notify(self.tr(u'There is no layer with a spatial extent in the project'), Qgis.Warning)
            return
        dlg = AutoLayoutToolDialogLayers(self.iface.mainWindow())
        if not dlg.exec():
            return
        layers = [project.mapLayer(layer_id) for layer_id in dlg.selected_layer_ids()]
        layers = [l for l in layers if l is not None]
        extent = self.layers_extent(layers, dlg.buffer_percent())
        if extent is None:
            self.notify(self.tr(u'Could not compute an extent for the selected layers'), Qgis.Warning)
            return
        self.draw_layout_from_extent(extent)

    def layers_extent(self, layers, buffer_percent):
        """
        Combined extent of the layers, in the project CRS, enlarged by buffer_percent on each side
        :param layers: list of QgsMapLayer
        :param buffer_percent: float, % of width / height added on each side
        :return: QgsRectangle or None
        """
        project = QgsProject.instance()
        dest_crs = project.crs()
        if not dest_crs.isValid():
            dest_crs = layers[0].crs()
        extent = None
        for layer in layers:
            if not layer_has_extent(layer):
                continue
            layer_extent = layer.extent()
            if layer.crs().isValid() and layer.crs() != dest_crs:
                try:
                    transform = QgsCoordinateTransform(layer.crs(), dest_crs, project)
                    layer_extent = transform.transformBoundingBox(layer_extent)
                except QgsCsException:
                    self.notify(self.tr(u"Layer '%s' could not be reprojected - ignored") % layer.name(),
                                Qgis.Warning)
                    continue
            if layer_extent.isNull() or not layer_extent.isFinite():
                continue
            if extent is None:
                extent = QgsRectangle(layer_extent)
            else:
                extent.combineExtentWith(layer_extent)
        if extent is None:
            return None

        width, height = extent.width(), extent.height()
        if width == 0 and height == 0:
            # Single point: use a fixed size around it
            half = MIN_HALF_EXTENT_M * QgsUnitTypes.fromUnitToUnitFactor(DISTANCE_M, dest_crs.mapUnits())
            half_width = half_height = half
        else:
            # Aligned points: give the null dimension the size of the other one
            half_width = (width or height) / 2
            half_height = (height or width) / 2
        # Buffer on each side
        half_width *= 1 + 2 * buffer_percent / 100
        half_height *= 1 + 2 * buffer_percent / 100
        center = extent.center()
        return QgsRectangle(center.x() - half_width, center.y() - half_height,
                            center.x() + half_width, center.y() + half_height)

    def draw_layout_from_extent(self, extent):
        """
        Creates the layout, then adds map, legend, scalebar and north arrow
        :param extent: QgsRectangle, map extent to display
        """
        try:
            self._draw_layout_from_extent(extent)
        except Exception as e:
            # Unexpected error: tell the user instead of failing silently in the python console
            self.notify(self.tr(u'Layout creation failed: %s') % e, Qgis.Critical, duration=0)
            self.log(traceback.format_exc(), Qgis.Critical)

    def _draw_layout_from_extent(self, extent):
        """
        :param extent: QgsRectangle
        """
        if not self.params_from_dialog:
            self.param_from_file()
        self.log(self.tr(u'AutoLayoutTool starts'))
        map_width = extent.xMaximum() - extent.xMinimum()
        map_height = extent.yMaximum() - extent.yMinimum()
        if (map_height == 0) or (map_width == 0):
            self.notify(self.tr(u'No loaded data - aborting'), Qgis.Warning)
            return
        # Create layout (not added to the project yet)
        project = QgsProject.instance()
        manager = project.layoutManager()
        layout = QgsPrintLayout(project)
        layout.initializeDefaults()
        # Determine and set best layout orientation
        landscape, layout_height, layout_width = self.compute_layout_orientation(extent, layout)
        # Map size: largest size with the extent proportions fitting in the page minus the margins.
        # Checked before asking about an existing layout, so that nothing is deleted if we have to abort.
        map_size = self.fit_map_size(extent.width(), extent.height(), layout_width, layout_height, self.margin)
        if map_size is None:
            self.notify(self.tr(u'Margin (%s mm) is too large for the page size - aborting') % self.margin,
                        Qgis.Warning, duration=10)
            return
        map_width, map_height = map_size
        # Layout name: ask what to do if a layout with the same name exists (may delete it)
        layout_name = self.resolve_layout_name(manager, self.layout_name)
        if layout_name is None:
            # User cancelled the operation
            self.log(self.tr(u'Cancelled by user'))
            return
        layout.setName(layout_name)
        # Add map
        map_real_height, map_real_width, x_offset, y_offset, my_map = self.add_map(
            extent, layout, layout_height, layout_width, map_height, map_width)
        if self.legend_placement != 4:
            # Add legend
            self.add_legend(layout, map_real_height, map_real_width, x_offset, y_offset, self.legend_title,
                            self.legend_placement)
        if self.scalebar_placement != 4:
            # Add scale bar
            self.add_scalebar(layout, map_real_height, map_real_width, my_map, x_offset, y_offset,
                              self.scalebar_placement)
        if self.north_placement != 4:
            # Add north arrow
            self.add_north_arrow(layout, map_real_height, map_real_width, x_offset, y_offset, self.north_placement)
        # Finally add layout to the project via its manager
        manager.addLayout(layout)
        self.iface.openLayoutDesigner(layout)
        self.log("♪♪ This is the end, my friend ♪♪")

    def resolve_layout_name(self, manager, layout_name):
        """
        Name of the new layout. If a layout with this name exists, ask the user to delete it
        or to use an incremented name.
        :param manager: QgsLayoutManager
        :param layout_name: str
        :return: name to use, or None if the user cancelled
        :rtype: str or None
        """
        existing = manager.layoutByName(layout_name)
        if existing is None:
            return layout_name

        # Next available incremented name, shown on the button
        next_name = self.get_unique_layout_name(manager, layout_name)

        msg_box = QMessageBox(self.iface.mainWindow())
        msg_box.setWindowTitle(self.tr(u'Layout already exists...'))
        msg_box.setText(self.tr(u"There's already a layout named '%s'") % layout_name)
        msg_box.setInformativeText(self.tr(u"What would you like to do?"))
        delete_btn = msg_box.addButton(self.tr(u"Delete existing"), MSGBOX_ROLE_DESTRUCTIVE)
        new_btn = msg_box.addButton(self.tr(u"Create '%s'") % next_name, MSGBOX_ROLE_ACCEPT)
        cancel_btn = msg_box.addButton(MSGBOX_CANCEL)
        msg_box.setDefaultButton(cancel_btn)
        msg_box.exec()

        clicked = msg_box.clickedButton()
        if clicked == delete_btn:
            manager.removeLayout(existing)
            self.log(self.tr(u"Previous layout named '%s' removed... ") % layout_name)
            return layout_name
        if clicked == new_btn:
            self.log(self.tr(u"Creating new layout '%s'") % next_name)
            return next_name
        # Cancel was clicked or dialog was closed
        return None

    def get_unique_layout_name(self, manager, base_name):
        """
        Generate a unique layout name by adding an increment suffix if needed
        :param manager: QgsProject.instance().layoutManager()
        :param base_name: The base layout name to check
        :return: A unique layout name (e.g., 'Automatic Layout', 'Automatic Layout (1)', etc.)
        :rtype: str
        """
        # All layouts (print layouts and reports): names must be unique among them
        existing_names = [layout.name() for layout in manager.layouts()]

        # If base name doesn't exist, use it directly
        if base_name not in existing_names:
            return base_name

        # Find the next available increment
        increment = 1
        while True:
            new_name = f"{base_name} ({increment})"
            if new_name not in existing_names:
                return new_name
            increment += 1

    def compute_layout_orientation(self, extent, layout):
        """
        Determine and set the best page orientation (landscape if the extent is wider than high)
        :param extent: QgsRectangle
        :param layout: QgsLayout
        :return: landscape, page height, page width (mm)
        :rtype: bool, float, float
        """

        self.log('Creating layout')
        map_width = extent.xMaximum() - extent.xMinimum()
        map_height = extent.yMaximum() - extent.yMinimum()
        landscape = map_width > map_height
        if self.debug: print("Landscape" if landscape else "Portrait")
        orientation = QgsLayoutItemPage.Orientation.Landscape if landscape \
            else QgsLayoutItemPage.Orientation.Portrait
        page = layout.pageCollection().page(0)
        # Empty page size = keep the size QGIS gives to new layouts (initializeDefaults())
        use_default = not self.page_size
        if not use_default and not page.setPageSize(self.page_size, orientation):
            self.notify(self.tr(u"Unknown page size '%s' - using QGIS default page size") % self.page_size,
                        Qgis.Warning)
            use_default = True
        if use_default:
            # Apply orientation to the default page size itself, which may have no name in the registry
            size = page.pageSize()
            short_side, long_side = sorted((size.width(), size.height()))
            if landscape:
                page.setPageSize(QgsLayoutSize(long_side, short_side, size.units()))
            else:
                page.setPageSize(QgsLayoutSize(short_side, long_side, size.units()))
        layout_width = layout.pageCollection().page(0).pageSize().width()
        layout_height = layout.pageCollection().page(0).pageSize().height()
        return landscape, layout_height, layout_width

    @staticmethod
    def fit_map_size(extent_width, extent_height, page_width, page_height, margin):
        """
        Largest map size with the proportions of the extent that fits in the page minus the margins.
        The margin is exact on the limiting axis and larger on the other one (the map is centred).
        :param extent_width: float, map units
        :param extent_height: float, map units
        :param page_width: float, mm
        :param page_height: float, mm
        :param margin: float, mm on each side
        :return: (map_width, map_height) in mm, or None if the margins leave no room for the map
        :rtype: tuple or None
        """
        available_width = page_width - 2 * margin
        available_height = page_height - 2 * margin
        if available_width <= 0 or available_height <= 0 or extent_width <= 0 or extent_height <= 0:
            return None
        ratio = extent_width / extent_height
        map_width = available_width
        map_height = map_width / ratio
        if map_height > available_height:
            map_height = available_height
            map_width = map_height * ratio
        return map_width, map_height

    def add_map(self, e, layout, layout_height, layout_width, map_height, map_width):
        """
        Add map to the layout, centred on the page
        :param e: QgsRectangle, map extent
        :param layout: QgsLayout
        :param layout_height: float, page height (mm)
        :param layout_width: float, page width (mm)
        :param map_height: float, map height (mm), margins already removed
        :param map_width: float, map width (mm), margins already removed
        :return: map height, map width, x offset, y offset (mm), map item
        :rtype: float, float, float, float, QgsLayoutItemMap
        """
        self.log('Adding map')
        my_map = QgsLayoutItemMap(layout)
        # Use attemptResize(), not setRect(): QGIS stores the item size internally and only attemptResize()
        # updates it. With setRect(), the stored size stays at 0 x 0 and refresh() shrinks the map to nothing
        # (setExtent() does not resize the map when its proportions already match the extent, as here).
        my_map.attemptResize(QgsLayoutSize(map_width, map_height, LAYOUT_MM))
        # setExtent() keeps the width and recomputes the height from the extent proportions
        my_map.setExtent(e)
        my_map.refresh()
        map_real_width = my_map.rect().size().width()
        map_real_height = my_map.rect().size().height()
        x_offset = (layout_width - map_real_width) / 2
        y_offset = (layout_height - map_real_height) / 2
        if self.debug: print("x_offset: %r / y_offset: %r" % (x_offset, y_offset))
        if self.debug: print("real_mapw: %r / real_maph: %r" % (map_real_width, map_real_height))
        my_map.setBackgroundColor(QColor(255, 255, 255, 255))
        my_map.setFrameEnabled(True)
        my_map.attemptMove(QgsLayoutPoint(x_offset, y_offset, LAYOUT_MM))
        layout.addLayoutItem(my_map)
        return map_real_height, map_real_width, x_offset, y_offset, my_map

    def add_legend(self, layout, map_real_height, map_real_width, x_offset, y_offset, legend_title, legend_placement):
        """
        Add legend to the layout, in a corner of the map
        :param layout: QgsLayout
        :param map_real_height: float, map height (mm)
        :param map_real_width: float, map width (mm)
        :param x_offset: float, map left position (mm)
        :param y_offset: float, map top position (mm)
        :param legend_title: str
        :param legend_placement: int, 0 top left, 1 top right, 2 bottom left, 3 bottom right
        :return: None
        """
        self.log(self.tr(u"Adding legend"))
        legend = QgsLayoutItemLegend(layout)
        legend.setTitle(legend_title)
        legend.setId("legend")
        legend.setAutoUpdateModel(False)
        group = legend.model().rootGroup()
        group.clear()
        self.fill_legend_group(group, QgsProject.instance().layerTreeRoot())
        layout.addItem(legend)
        legend.adjustBoxSize()
        legend.setFrameEnabled(True)

        # The legend size is often not known yet at this point (sizeWithUnits() returns 0), so it can not be
        # used to compute the position. Instead, anchor the legend by the corner matching its placement:
        # attemptMove() places this reference point, and it stays fixed when the legend is resized later.
        left, top = x_offset, y_offset
        right, bottom = x_offset + map_real_width, y_offset + map_real_height
        corners = {
            0: (REF_UPPER_LEFT, left, top),
            1: (REF_UPPER_RIGHT, right, top),
            2: (REF_LOWER_LEFT, left, bottom),
            3: (REF_LOWER_RIGHT, right, bottom),
        }
        reference, x, y = corners.get(legend_placement, corners[0])
        legend.setReferencePoint(reference)
        legend.attemptMove(QgsLayoutPoint(x, y, LAYOUT_MM))
        legend.refresh()

    def fill_legend_group(self, target, source):
        """
        Recursively copy visible groups and layers of the project layer tree into the legend tree.
        Uses QgsLayerTree.isGroup()/isLayer() instead of comparing nodeType() to ints,
        which does not work with PyQt6 enums (QGIS 4).
        :param target: QgsLayerTreeGroup, legend group to fill
        :param source: QgsLayerTreeGroup, project group to read
        """
        for node in source.children():
            if not node.itemVisibilityChecked():
                continue
            if QgsLayerTree.isGroup(node):
                subgroup = target.addGroup(node.name())
                self.fill_legend_group(subgroup, node)
                if not subgroup.children():
                    # No visible layer in this group: do not show an empty group title
                    target.removeChildNode(subgroup)
            elif QgsLayerTree.isLayer(node) and node.layer() is not None:
                target.addLayer(node.layer())

    def add_scalebar(self, layout, map_real_height, map_real_width, my_map, x_offset, y_offset, scalebar_placement):
        """
        Add scalebar to the layout
        :param layout: QgsLayout
        :param map_real_height: float
        :param map_real_width: float
        :param my_map: QgsLayoutItemMap
        :param x_offset: float
        :param y_offset: float
        :return: None
        """
        self.log(self.tr(u'Adding scale bar'))
        # The constructor already calls applyDefaultSettings(). Calling it again after applyDefaultSize()
        # (as before) resets the units to "unknown", and forcing km by dividing by 1000 assumed metres.
        scalebar = QgsLayoutItemScaleBar(layout)
        scalebar.setStyle('Single Box')
        scalebar.setLinkedMap(my_map)
        # Let QGIS pick the unit from the map CRS and scale: m / km for metric and geographic CRS
        # (distances are computed on the ellipsoid), ft / mi for imperial CRS
        units = scalebar.guessUnits()
        # Sets units, a rounded segment length (bar = 1/5 of map width) and resizes the item
        scalebar.applyDefaultSize(units)
        try:
            scalebar.setUnitLabel(QgsUnitTypes.toAbbreviatedString(units))
        except (AttributeError, TypeError):
            # Keep the label set by applyDefaultSize()
            pass
        scalebar.update()
        layout.addLayoutItem(scalebar)
        if scalebar_placement == 0:
            # up left
            scalebar.attemptMove(QgsLayoutPoint(3 + x_offset,
                                                y_offset - scalebar.rect().size().height() + 15,
                                                LAYOUT_MM))

        elif scalebar_placement == 1:
            #  up right
            scalebar.attemptMove(QgsLayoutPoint(map_real_width + x_offset - scalebar.rect().size().width() - 2,
                                                y_offset - scalebar.rect().size().height() + 15,
                                                LAYOUT_MM))
        elif scalebar_placement == 2:
            # bottom left
            scalebar.attemptMove(QgsLayoutPoint(3 + x_offset,
                                                map_real_height + y_offset - scalebar.rect().size().height() - 2,
                                                LAYOUT_MM))
        elif scalebar_placement == 3:
            # bottom right
            scalebar.attemptMove(QgsLayoutPoint(map_real_width + x_offset - scalebar.rect().size().width() - 2,
                                                map_real_height + y_offset - scalebar.rect().size().height() - 2,
                                                LAYOUT_MM))

    def add_north_arrow(self, layout, map_real_height, map_real_width, x_offset, y_offset, north_placement):
        """
        Adds north arrow to the layout
        :param layout: QgsLayout
        :param map_real_height: float
        :param x_offset: float
        :param y_offset: float
        :return: None
        """
        self.log(self.tr(u"Adding north arrow"))
        north = QgsLayoutItemPicture(layout)
        north.setPicturePath(self.plugin_dir + "/images/north-arrow.svg")
        layout.addLayoutItem(north)
        north.attemptResize(QgsLayoutSize(8, 13, LAYOUT_MM))
        if north_placement == 0:
            # up left
            north.attemptMove(QgsLayoutPoint(3 + x_offset,
                                             3 + y_offset,
                                             LAYOUT_MM))
        elif north_placement == 1:
            # up right
            north.attemptMove(QgsLayoutPoint(map_real_width + x_offset - north.rect().size().width() - 3,
                                             3 + y_offset, LAYOUT_MM))
        elif north_placement == 2:
            # bottom left
            north.attemptMove(QgsLayoutPoint(3 + x_offset,
                                             map_real_height + y_offset - north.rect().size().height() - 2,
                                             LAYOUT_MM))
        elif north_placement == 3:
            # bottom right
            north.attemptMove(QgsLayoutPoint(map_real_width + x_offset - north.rect().size().width() - 3,
                                             map_real_height + y_offset - north.rect().size().height() - 2,
                                             LAYOUT_MM))

    def apply_toolbar_visibility(self, show_config, show_help):
        """
        Apply toolbar icons visibility (without affecting menu)
        :param show_config: bool - Show config icon in toolbar
        :param show_help: bool - Show help icon in toolbar
        """
        # Only hide toolbar icons, not menu entries
        # Actions are visible in menu, but their toolbar visibility
        # is controlled by adding or removing them from toolbar

        # Remove actions from toolbar if necessary
        if not show_config:
            self.toolbar.removeAction(self.config_action)
        elif show_config and self.config_action not in self.toolbar.actions():
            # Keep the order: ... layers, config, help
            if self.help_action in self.toolbar.actions():
                self.toolbar.insertAction(self.help_action, self.config_action)
            else:
                self.toolbar.addAction(self.config_action)

        if not show_help:
            self.toolbar.removeAction(self.help_action)
        elif show_help and self.help_action not in self.toolbar.actions():
            self.toolbar.addAction(self.help_action)

    def load_toolbar_visibility_preferences(self):
        """
        Load toolbar icons visibility preferences (QGIS profile settings or defaults)
        """
        ui_values = settings.load()["UI_OPTIONS"]
        self.apply_toolbar_visibility(settings.to_bool(ui_values.get("cb_show_config_icon"), True),
                                      settings.to_bool(ui_values.get("cb_show_help_icon"), True))

    def param_from_file(self):
        """
        Load default or custom params (custom params are stored in the QGIS profile)
        :return:
        """
        file_values = settings.load()["ITEMS_PLACEMENT"]
        self.north_placement = int(file_values["cbb_north_value"])
        self.scalebar_placement = int(file_values["cbb_scalebar_value"])
        self.legend_placement = int(file_values["cbb_legend_value_value"])
        self.legend_title = self.tr(file_values["le_legend_title_value"])
        self.margin = int(file_values["sb_margin_value_value"])
        self.layout_name = self.tr(file_values["le_layout_name_value"])
        # page size registry name; empty string means QGIS default page size
        self.page_size = file_values.get("cbb_page_format_value", "")
